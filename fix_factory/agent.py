import concurrent.futures
import json
import logging
import os
import uuid
from google import genai
from google.adk.agents import LlmAgent
from google.adk.tools import FunctionTool
from google.adk import Runner
from google.adk.sessions import InMemorySessionService
from google.genai import types as genai_types
from opentelemetry import trace

try:
    from shared.otel_setup import setup_tracer
    _tracer = setup_tracer("fix-factory")
except Exception:
    _tracer = trace.get_tracer("ripple.fix-factory")

logger = logging.getLogger(__name__)

if os.environ.get("GEMINI_API_KEY") and not os.environ.get("GOOGLE_API_KEY"):
    os.environ["GOOGLE_API_KEY"] = os.environ["GEMINI_API_KEY"]


def _gemini_client():
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if api_key:
        return genai.Client(api_key=api_key)
    return genai.Client(vertexai=True, project=os.environ["GOOGLE_CLOUD_PROJECT"], location="us-central1")


def _default_gemini(prompt: str) -> tuple[str, str, str]:
    client = _gemini_client()
    ex = concurrent.futures.ThreadPoolExecutor(max_workers=1)
    try:
        text = ex.submit(
            lambda: client.models.generate_content(
                model="gemini-3-flash-preview", contents=prompt
            ).text.strip()
        ).result(timeout=20)
        if text.startswith("```"):
            text = text.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        try:
            parsed = json.loads(text)
            return parsed.get("old_line", ""), parsed.get("new_line", ""), parsed.get("fix_explanation", "")
        except (json.JSONDecodeError, KeyError) as e:
            logger.warning("_default_gemini parse failed: %s | raw: %.200s", e, text)
            return "", "", "Fix generated by Gemini."
    except Exception as e:
        logger.warning("_default_gemini (fix-factory) failed or timed out: %s", e)
        return "", "", "Fix generated by Gemini."
    finally:
        ex.shutdown(wait=False, cancel_futures=True)


def _programmatic_fix(matching_lines: list, incident_id: str) -> tuple[str, str, str]:
    """Regex-based fix — no Gemini. Used when Gemini times out so MRs still get created."""
    import re
    if not matching_lines:
        return "", "", ""
    line = matching_lines[0].get("content", "")
    m = re.search(r'((?:requests|httpx)\.\w+\()([^)]*?)(\))', line)
    if m and "timeout=" not in m.group(0):
        args = m.group(2)
        new_call = m.group(1) + (args + ", timeout=5" if args.strip() else "timeout=5") + m.group(3)
        new_line = line[:m.start()] + new_call + line[m.end():]
        explanation = f"Add timeout=5 to prevent indefinite hanging — directly replicates {incident_id} failure mode."
        return line, new_line, explanation
    return "", "", ""


def _fetch_fix_precedents(gitlab_namespace: str) -> list[dict]:
    """Fetch closed MRs that fixed similar patterns in this service - used by the fix agent."""
    from fix_factory.tools.gitlab_history import get_fix_precedents
    token = os.environ.get("GITLAB_TOKEN", "")
    return get_fix_precedents(gitlab_namespace, token)


def call_fix_adk(hit: dict, traces: list[dict]) -> tuple[str, str, str]:
    """Generate a code fix using an ADK LlmAgent with a GitLab history FunctionTool.

    The agent can call the tool to fetch how this team has fixed similar patterns before.
    """
    ctx = hit.get("incident_context", {})
    lines = hit.get("matching_lines", [])
    namespace = hit.get("gitlab_namespace", hit.get("service", ""))

    def _get_precedents() -> list[dict]:
        return _fetch_fix_precedents(namespace)

    agent = LlmAgent(
        name="ripple_fix_agent",
        model="gemini-3-flash-preview",
        instruction=(
            "You are a senior engineer generating targeted code fixes grounded in production incident history. "
            "A GitLab history tool is available - use it if you need to see how this team has fixed "
            "similar patterns before. "
            "Return a JSON object with exactly: "
            "old_line (the exact line to replace including whitespace), "
            "new_line (the replacement line with timeout=5 added), "
            "fix_explanation (one sentence citing the incident ID). "
            "No markdown, no extra fields."
        ),
        tools=[FunctionTool(_get_precedents)],
    )

    session_service = InMemorySessionService()
    runner = Runner(
        app_name="ripple-fix-factory",
        agent=agent,
        session_service=session_service,
        auto_create_session=True,
    )

    prompt = (
        f"Generate a fix for this dangerous pattern.\n\n"
        f"File: {hit['file_path']}\n"
        f"Matching lines: {json.dumps(lines, indent=2)}\n\n"
        f"Incident context: {json.dumps(ctx, indent=2)}\n\n"
        f"Dynatrace traces: {json.dumps(traces[:2], indent=2) if traces else 'None available.'}\n\n"
        f"Use the history tool if you need fix precedents. Return only the JSON object."
    )
    message = genai_types.Content(
        role="user", parts=[genai_types.Part(text=prompt)])

    text = ""
    for event in runner.run(user_id="system", session_id=str(uuid.uuid4()), new_message=message):
        if event.is_final_response() and event.content and event.content.parts:
            text = event.content.parts[0].text.strip()
            break

    if text.startswith("```"):
        text = text.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
    try:
        parsed = json.loads(text)
        return parsed.get("old_line", ""), parsed.get("new_line", ""), parsed.get("fix_explanation", "")
    except (json.JSONDecodeError, KeyError) as e:
        logger.warning("call_fix_adk parse failed: %s | raw: %.200s", e, text)
        return "", "", "Fix generated by Gemini."


def generate_fix(
    hit: dict,
    traces: list[dict],
    precedents: list[dict],
    _gemini_fn=None,
) -> dict:
    ctx = hit.get("incident_context", {})
    lines = hit.get("matching_lines", [])

    if _gemini_fn is None:
        _gemini_fn = _default_gemini
    history = hit.get("per_service_history", [])

    prompt = f"""You are a senior engineer generating a targeted code fix.

DANGEROUS PATTERN FOUND:
File: {hit['file_path']}
Matching lines: {json.dumps(lines, indent=2)}

INCIDENT CONTEXT:
{json.dumps(ctx, indent=2)}

DYNATRACE TRACES:
{json.dumps(traces[:3], indent=2) if traces else "No trace data available."}

PREVIOUS FIX PRECEDENTS:
{json.dumps(precedents[:3], indent=2) if precedents else "No precedents found."}

PER-SERVICE HISTORY:
{json.dumps(history, indent=2) if history else "No history."}

Generate a minimal fix. Return JSON with exactly three fields:
- old_line: the exact line of code to replace, including leading whitespace, exactly as it appears in the file
- new_line: the replacement line, including leading whitespace (add timeout=5 to the HTTP call)
- fix_explanation: one sentence citing the incident ID and what the fix prevents

IMPORTANT: In fix_explanation, always cite the incident_id from INCIDENT CONTEXT (e.g. {ctx.get('incident_id', 'unknown')}).
Never use internal trace IDs or correlation IDs from the Dynatrace trace data.

Respond with only the JSON object, no markdown."""

    old_line, new_line, explanation = _gemini_fn(prompt)

    # Gemini timed out or failed — fall back to regex-based fix
    if not old_line:
        incident_id = ctx.get("incident_id", "unknown")
        old_line, new_line, explanation = _programmatic_fix(lines, incident_id)

    patch = f"-{old_line}\n+{new_line}" if old_line and new_line else ""
    return {"old_line": old_line, "new_line": new_line, "patch": patch, "fix_explanation": explanation}


def run_with_correction(
    hit: dict,
    traces: list[dict],
    precedents: list[dict],
    max_iterations: int = 3,
    _fix_fn=None,
    _eval_fn=None,
    _mr_fn=None,
    _store_fn=None,
) -> dict:
    from fix_factory.evaluator import evaluate_fix
    from fix_factory.tools.gitlab_mr import create_mr
    from fix_factory.tools.mongodb_outcomes import store_outcome

    if _fix_fn is None:
        _fix_fn = generate_fix
    if _eval_fn is None:
        _eval_fn = evaluate_fix
    if _mr_fn is None:
        _mr_fn = create_mr
    if _store_fn is None:
        _store_fn = store_outcome

    last_rationale = ""
    extra_context = ""
    fix: dict = {"old_line": "", "new_line": "",
                 "patch": "", "fix_explanation": ""}

    with _tracer.start_as_current_span("ripple.fix_factory.run_with_correction") as span:
        span.set_attribute("service", hit.get("service", ""))
        span.set_attribute("file_path", hit.get("file_path", ""))
        span.set_attribute("max_iterations", max_iterations)

        for i in range(max_iterations):
            try:
                fix = _fix_fn(hit, traces, precedents)
                if extra_context:
                    fix["fix_explanation"] += f" (retry {i+1}: {extra_context})"

                evaluation = _eval_fn(hit, fix["patch"])

                if evaluation["passed"]:
                    import os
                    gl_token = os.environ.get("GITLAB_TOKEN", "")
                    namespace = hit.get("gitlab_namespace", hit["service"])
                    evaluated_on = evaluation.get(
                        "evaluated_on", "incident_context")
                    mr_url = _mr_fn(
                        namespace, gl_token, hit["file_path"], fix["old_line"], fix["new_line"], hit["incident_context"], evaluated_on)
                    outcome = {
                        "service": hit["service"],
                        "file_path": hit["file_path"],
                        "mr_url": mr_url,
                        "self_correction_passed": True,
                        "correction_iterations": i + 1,
                        "failure_reason": None,
                        "evaluated_on": evaluated_on,
                    }
                    span.set_attribute("self_correction.passed", True)
                    span.set_attribute("correction.iterations", i + 1)
                    span.set_attribute("evaluated_on", evaluated_on)
                    _store_fn(outcome)
                    return {**fix, **outcome}

                last_rationale = evaluation["rationale"]
                extra_context = last_rationale
            except Exception as e:
                last_rationale = f"Error on iteration {i + 1}: {e}"
                extra_context = last_rationale

        span.set_attribute("self_correction.passed", False)
        span.set_attribute("correction.iterations", max_iterations)

    outcome = {
        "service": hit["service"],
        "file_path": hit["file_path"],
        "mr_url": None,
        "self_correction_passed": False,
        "correction_iterations": max_iterations,
        "failure_reason": last_rationale,
    }
    _store_fn(outcome)
    return {**fix, **outcome}
